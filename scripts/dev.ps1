<#
.SYNOPSIS
    Local development launcher for ros-ddns.

.DESCRIPTION
    Loads credentials from build\secrets\ros-ddns.env, then validates the config
    (-Check) or starts the daemon in the background with its logs under build\logs.
    A missing configuration is generated by the daemon on start.

    Files used by this script:
      build\bin\ros-ddns.exe           binary (use -Build or the go wrapper)
      build\configs\config.local.yaml  local config, generated on first start (optional env overrides)
      build\secrets\ros-ddns.env       KEY=VALUE credentials, never printed
      build\data\test-state.json       runtime state plus its .lock
      build\logs\                      daemon stdout/stderr logs

.EXAMPLE
    .\scripts\dev.ps1 -Build -Check

.EXAMPLE
    .\scripts\dev.ps1

.EXAMPLE
    .\scripts\dev.ps1 -Stop
#>
[CmdletBinding()]
param(
    [switch]$Check,
    [switch]$Foreground,
    [switch]$Stop,
    [switch]$Build,
    [string]$Config
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$bin = Join-Path $root 'build\bin\ros-ddns.exe'
if (-not $Config) { $Config = Join-Path $root 'build\configs\config.local.yaml' }
$envFile = Join-Path $root 'build\secrets\ros-ddns.env'
$logDir = Join-Path $root 'build\logs'
$lockFile = Join-Path $root 'build\data\test-state.json.lock'

function Import-DotEnv([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path)) {
        Write-Warning "env file not found: $Path"
        return
    }
    foreach ($line in [System.IO.File]::ReadAllLines($Path)) {
        $trimmed = $line.Trim()
        if ($trimmed -eq '' -or $trimmed.StartsWith('#')) { continue }
        if ($trimmed -match '^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$') {
            $name = $Matches[1]
            $value = $Matches[2].Trim()
            if ($value.Length -ge 2) {
                $quote = $value.Substring(0, 1)
                if (($quote -eq '"' -or $quote -eq "'") -and $value.EndsWith($quote)) {
                    $value = $value.Substring(1, $value.Length - 2)
                }
            }
            Set-Item -Path "Env:$name" -Value $value
        }
    }
}

function Quote-Arg([string]$Value) {
    if ($Value -match '\s') { return '"{0}"' -f $Value }
    return $Value
}

if ($Stop) {
    if (-not (Test-Path -LiteralPath $lockFile)) {
        Write-Host "no lock file: $lockFile"
        return
    }
    $info = Get-Content -LiteralPath $lockFile -Raw | ConvertFrom-Json
    $proc = Get-Process -Id $info.pid -ErrorAction SilentlyContinue
    if (-not $proc) {
        Write-Host "pid $($info.pid) is not running; stale lock left in place"
        return
    }
    Stop-Process -Id $info.pid -Force
    $proc.WaitForExit(5000) | Out-Null
    Write-Host "stopped pid $($info.pid)"
    return
}

Import-DotEnv $envFile

if ($Build) {
    & (Join-Path $root 'scripts\go.cmd') build -o $bin ./cmd/ros-ddns
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
}
if (-not (Test-Path -LiteralPath $bin)) {
    throw "binary not found: $bin (run with -Build or: .\scripts\go.cmd build -o build\bin\ros-ddns.exe ./cmd/ros-ddns)"
}

$toolArgs = @('-config', (Quote-Arg $Config))
if ($Check) {
    & $bin @toolArgs -check
    exit $LASTEXITCODE
}
if ($Foreground) {
    & $bin @toolArgs
    exit $LASTEXITCODE
}

New-Item -ItemType Directory -Force $logDir | Out-Null
$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$outLog = Join-Path $logDir "daemon-$stamp.out.log"
$errLog = Join-Path $logDir "daemon-$stamp.log"
$proc = Start-Process -FilePath $bin -ArgumentList $toolArgs -WorkingDirectory $root `
    -RedirectStandardOutput $outLog -RedirectStandardError $errLog -PassThru -WindowStyle Hidden
Write-Host "started ros-ddns pid $($proc.Id)"
Write-Host "  config: $Config"
Write-Host "  stderr: $errLog  (runtime logs)"
Write-Host "  stdout: $outLog"
Write-Host "  stop:   .\scripts\dev.ps1 -Stop"
